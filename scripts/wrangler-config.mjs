// @ts-check
// Generate a local-only wrangler config that carries the real D1 database id, so the id never
// enters the repository (decision D53). The committed apps/web/wrangler.toml keeps the placeholder
// `REPLACE_WITH_D1_ID`; this writes apps/web/.local/wrangler.toml (git-ignored) with the id filled in
// and the paths rewritten to resolve from apps/web/.local/.
//
// Usage: node scripts/wrangler-config.mjs
// The id comes from the env var D1_DATABASE_ID (wins) or config/cloudflare.local.json
// ({"d1DatabaseId": "..."}, git-ignored). The id is never printed.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLACEHOLDER = 'REPLACE_WITH_D1_ID';
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** Rewrites that make the committed config's relative paths resolve from apps/web/.local/. */
const PATH_REWRITES = /** @type {const} */ ([
  [/^(main\s*=\s*)"src\/worker\.js"/m, '$1"../src/worker.js"', 'main'],
  [/^(directory\s*=\s*)"\.\/dist"/m, '$1"../dist"', 'assets directory'],
  [/^(migrations_dir\s*=\s*)"migrations"/m, '$1"../migrations"', 'migrations_dir'],
]);

/**
 * Whether a value looks like a D1 database id (a UUID).
 * @param {unknown} id
 * @returns {boolean}
 */
export function isValidD1Id(id) {
  return typeof id === 'string' && UUID_RE.test(id);
}

/**
 * Render the local wrangler config from the committed template. Pure.
 * @param {string} templateText contents of apps/web/wrangler.toml
 * @param {{d1DatabaseId: string}} options
 * @returns {string}
 * @throws {Error} when the id is not a UUID, or the template lacks an expected line
 */
export function renderConfig(templateText, { d1DatabaseId }) {
  if (!isValidD1Id(d1DatabaseId)) throw new Error('d1DatabaseId must be a UUID');
  let out = templateText;
  for (const [re, replacement, label] of PATH_REWRITES) {
    if (!re.test(out)) throw new Error(`template lacks the expected ${label} line`);
    out = out.replace(re, replacement);
  }
  if (!out.includes(`"${PLACEHOLDER}"`)) throw new Error(`template lacks the ${PLACEHOLDER} placeholder`);
  // replacer function: the id is inserted literally, never interpreted as a replacement pattern
  out = out.replace(`"${PLACEHOLDER}"`, () => `"${d1DatabaseId}"`);
  return `# Generated by scripts/wrangler-config.mjs from apps/web/wrangler.toml. Git-ignored: it holds the D1 id.\n${out}`;
}

/**
 * Find the D1 id: env D1_DATABASE_ID wins, else config/cloudflare.local.json.
 * @param {string} root repository root
 * @param {Record<string, string | undefined>} env
 * @returns {string | null} the raw value (possibly malformed), or null when neither source has one
 */
export function readD1Id(root, env) {
  const fromEnv = env.D1_DATABASE_ID?.trim();
  if (fromEnv) return fromEnv;
  const file = join(root, 'config', 'cloudflare.local.json');
  if (!existsSync(file)) return null;
  let data;
  try {
    data = JSON.parse(readFileSync(file, 'utf8'));
  } catch {
    throw new Error('config/cloudflare.local.json is not valid JSON (expected {"d1DatabaseId": "<uuid>"})');
  }
  const v = typeof data?.d1DatabaseId === 'string' ? data.d1DatabaseId.trim() : '';
  return v === '' ? null : v;
}

/**
 * Write apps/web/.local/wrangler.toml.
 * @param {{root?: string, env?: Record<string, string | undefined>}} [opts]
 * @returns {{outPath: string}}
 * @throws {Error} with a message naming both id sources when the id is missing or malformed
 */
export function main(opts = {}) {
  const root = resolve(opts.root ?? ROOT);
  const env = opts.env ?? process.env;
  const id = readD1Id(root, env);
  if (id === null) {
    throw new Error('no D1 database id: set env D1_DATABASE_ID or put {"d1DatabaseId": "<uuid>"} in config/cloudflare.local.json');
  }
  if (!isValidD1Id(id)) {
    throw new Error('the D1 database id is not a UUID (from env D1_DATABASE_ID or config/cloudflare.local.json); copy it from the Cloudflare dashboard');
  }
  const template = readFileSync(join(root, 'apps', 'web', 'wrangler.toml'), 'utf8');
  const outPath = join(root, 'apps', 'web', '.local', 'wrangler.toml');
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, renderConfig(template, { d1DatabaseId: id }), 'utf8');
  return { outPath };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { outPath } = main();
    console.log(`wrangler config -> ${relative(ROOT, outPath)}`);
  } catch (err) {
    console.error(`wrangler-config: ${err instanceof Error ? err.message : err}`);
    process.exit(1);
  }
}
