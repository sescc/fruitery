// @ts-check
// Generate the D1 seed as plain INSERT statements (decision D55: seeding is not a migration, so no
// personal data is ever committed).
//
// Usage: node scripts/gen-seed-sql.mjs [inputPath] [--out outPath]
//   input  default: config/seed.local.json when it exists, else the example SEED from core
//   output default: apps/web/.local/seed.sql (git-ignored)
// Statements are INSERT OR IGNORE, so re-running never overwrites rows edited since (LWW stays safe).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SEED, validateItem } from '../packages/core/index.js';
import { TABLES, toRow } from '../apps/web/src/rows.js';

/** @typedef {import('../apps/web/src/rows.js').Kind} Kind */

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const LOCAL_SEED_PATH = join(ROOT, 'config', 'seed.local.json');
export const DEFAULT_OUT_PATH = join(ROOT, 'apps', 'web', '.local', 'seed.sql');

/**
 * @param {string | number | null | undefined} v
 * @returns {string} an SQL literal
 */
function literal(v) {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') {
    if (!Number.isFinite(v)) throw new RangeError('non-finite number in seed');
    return String(v);
  }
  return `'${String(v).replace(/'/g, "''")}'`;
}

/**
 * @param {Kind} kind
 * @param {any} entity
 * @returns {string}
 */
function insert(kind, entity) {
  const { table, columns } = TABLES[kind];
  const row = toRow(kind, entity);
  return `INSERT OR IGNORE INTO ${table} (${columns.join(', ')}) VALUES (${columns.map((c) => literal(row[c])).join(', ')});`;
}

/**
 * Deterministic seed SQL for a dataset of the same shape as core's `SEED`.
 * @param {{workspaces: any[], groups: any[], items: any[], settings: any}} data
 * @returns {string}
 * @throws {Error} when an item is invalid
 */
export function generateSeedSql(data) {
  const problems = [];
  for (const item of data.items) {
    const errors = validateItem(item, { groups: data.groups });
    if (errors.length > 0) problems.push(`${item?.id}: ${errors.map((e) => `${e.field} ${e.code}`).join(', ')}`);
  }
  if (problems.length > 0) throw new Error(`invalid seed items:\n${problems.join('\n')}`);
  const lines = [
    '-- Generated by scripts/gen-seed-sql.mjs. Do not commit (git-ignored). Safe to re-run: INSERT OR IGNORE.',
    ...data.workspaces.map((e) => insert('workspace', e)),
    ...data.groups.map((e) => insert('group', e)),
    ...data.items.map((e) => insert('item', e)),
    insert('settings', data.settings),
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * Resolve the seed dataset: an explicit path, else the local personal seed, else the example SEED.
 * @param {string | undefined} inputPath
 * @returns {{data: any, source: string}}
 */
export function loadSeed(inputPath) {
  const path = inputPath ?? (existsSync(LOCAL_SEED_PATH) ? LOCAL_SEED_PATH : undefined);
  if (path === undefined) return { data: SEED, source: 'example SEED' };
  return { data: JSON.parse(readFileSync(path, 'utf8')), source: path === LOCAL_SEED_PATH ? 'config/seed.local.json' : path };
}

/**
 * @param {string[]} argv arguments after the script name
 * @returns {{outPath: string, count: string, source: string}}
 */
export function main(argv) {
  let input;
  let outPath = DEFAULT_OUT_PATH;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--out') outPath = resolve(argv[++i]);
    else input = resolve(argv[i]);
  }
  const { data, source } = loadSeed(input);
  const sql = generateSeedSql(data);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, sql, 'utf8');
  return { outPath, source, count: `${data.workspaces.length} workspaces, ${data.groups.length} groups, ${data.items.length} items` };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const r = main(process.argv.slice(2));
  console.log(`seed: ${r.count} from ${r.source} -> ${relative(ROOT, r.outPath)}`);
}
